import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { delimiter, dirname, join } from "node:path";
import { expectDefined } from "@openclaw/normalization-core";
import { afterEach, describe, expect, it } from "vitest";
import { useAutoCleanupTempDirTracker } from "../helpers/temp-dir.js";
import {
  readWorkflow,
  readWorkflowOutputs,
  requiredWorkflowStep,
  runGit,
  runWorkflowShellScript,
  writeExecutable,
  type WorkflowStep,
} from "./ci-workflow.test-support.js";

const tempDirs = useAutoCleanupTempDirTracker(afterEach);
const version = "2099.1.1";
const validator = "packages/gateway-protocol/src/compiled/protocol.generated/predicates.js";
const header = "// Generated by pnpm gateway:validators:gen; do not edit.\n";
const jobs = readWorkflow(".github/workflows/atlas-sync-stable.yml").jobs;
const steps: WorkflowStep[] = [...jobs.prepare.steps, ...jobs["open-pr"].steps];

function fixture(kind: "clean" | "generated" | "mixed" | "no-marker" | "deleted") {
  const root = tempDirs.make("openclaw-atlas-sync-");
  const repo = join(root, "repo");
  const bin = join(root, "bin");
  mkdirSync(join(repo, dirname(validator)), { recursive: true });
  mkdirSync(bin);
  const git = (...args: string[]) => runGit(repo, args);
  const write = (file: string, content: string) => writeFileSync(join(repo, file), content);
  const commit = (title: string) => {
    git("add", "--all");
    git("commit", "-m", title);
    return git("rev-parse", "HEAD");
  };
  git("init", "--initial-branch=main");
  git("config", "user.name", "Atlas Fixture");
  git("config", "user.email", "atlas-fixture@example.invalid");
  git("config", "commit.gpgSign", "false");
  git("config", "core.hooksPath", "/dev/null");
  git("config", `url.${repo}.insteadOf`, "https://github.com/openclaw/openclaw.git");
  write(validator, `${header}// common\n`);
  write("schema.ts", "// common source\n");
  const ancestor = commit("common");
  write("atlas-schema.ts", "// Atlas definition\n");
  if (kind !== "clean") {
    write(validator, `${header}// Atlas seed\n`);
  }
  if (kind === "mixed") {
    write("schema.ts", "// Atlas source\n");
  }
  const base = commit("Atlas");
  git("checkout", "--detach", ancestor);
  write("upstream-schema.ts", "// OpenClaw definition\n");
  if (kind === "deleted") {
    git("rm", validator);
  } else {
    write(validator, `${kind === "no-marker" ? "" : header}// OpenClaw seed\n`);
  }
  if (kind === "mixed") {
    write("schema.ts", "// OpenClaw source\n");
  }
  const upstream = commit("OpenClaw");
  git("tag", `v${version}`);
  git("checkout", "main");

  const output = join(root, "output");
  const summary = join(root, "summary");
  function run(name: string, cwd = repo, env: NodeJS.ProcessEnv = {}) {
    const step = requiredWorkflowStep(steps, name);
    return runWorkflowShellScript(expectDefined(step.run, name), {
      cwd,
      env: {
        ...process.env,
        PATH: `${bin}${delimiter}${process.env.PATH ?? ""}`,
        GIT_ALLOW_PROTOCOL: "file",
        GITHUB_OUTPUT: output,
        GITHUB_STEP_SUMMARY: summary,
        RUNNER_TEMP: root,
        VERSION: version,
        ...env,
      },
    });
  }
  return { root, repo, bin, git, run, base, upstream, output, summary };
}

describe.skipIf(process.platform !== "linux")("Atlas stable sync candidate", () => {
  it.each(["clean", "generated"] as const)("commits a %s merge", (kind) => {
    const { root, repo, bin, git, run, base, upstream, output } = fixture(kind);
    expect(run("Assemble candidate")).toMatchObject({ status: 0 });
    expect(readWorkflowOutputs(output)).toEqual(
      kind === "generated" ? { base, regenerate: "true" } : { base },
    );

    if (kind === "generated") {
      expect(git("diff", "--name-only", "--diff-filter=U")).toBe(validator);
      writeExecutable(join(bin, "corepack"), ["#!/usr/bin/env bash", 'test "$*" = enable']);
      writeExecutable(join(bin, "pnpm"), [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        'case "$*" in',
        '  "install --frozen-lockfile") ;;',
        `  gateway:validators:gen) cat atlas-schema.ts upstream-schema.ts > ${validator} ;;`,
        "  *) exit 1 ;;",
        "esac",
      ]);
      expect(run("Regenerate Gateway validators")).toMatchObject({ status: 0 });
    }

    expect(run("Commit candidate")).toMatchObject({ status: 0 });
    const head = git("rev-parse", "HEAD");
    expect(readWorkflowOutputs(output).head).toBe(head);
    expect(git("show", "-s", "--format=%P", head)).toBe(`${base} ${upstream}`);
    expect(git("show", `HEAD:${validator}`)).toBe(
      kind === "generated"
        ? "// Atlas definition\n// OpenClaw definition"
        : `${header}// OpenClaw seed`,
    );

    const receiver = join(root, "receiver");
    mkdirSync(receiver);
    runGit(receiver, ["init"]);
    runGit(receiver, ["fetch", repo, base]);
    runGit(receiver, ["checkout", "--detach", "FETCH_HEAD"]);
    expect(run("Bundle candidate", repo, { BASE: base })).toMatchObject({ status: 0 });
    expect(run("Import candidate", receiver, { HEAD: head })).toMatchObject({ status: 0 });
    expect(runGit(receiver, ["rev-parse", "HEAD", "FETCH_HEAD"])).toBe(`${base}\n${head}`);
  });

  it.each(["mixed", "no-marker", "deleted"] as const)("reports a %s conflict", (kind) => {
    const { git, run, base, output, summary } = fixture(kind);
    expect(run("Assemble candidate")).toMatchObject({ status: 0 });
    expect(readWorkflowOutputs(output)).toEqual({ conflict: "true" });
    expect(run("Report merge conflict")).toMatchObject({ status: 1 });
    const report = readFileSync(summary, "utf8");
    expect(report).toContain(validator);
    if (kind === "mixed") {
      expect(report).toContain("schema.ts");
    }
    expect(git("rev-parse", "HEAD")).toBe(base);
    expect(git("diff", "--name-only", "--diff-filter=U")).toContain(validator);
  });
});
